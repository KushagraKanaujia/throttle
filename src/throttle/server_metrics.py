class MetricsCollectionError(ValueError):
    """A fixed-code collector failure that never reflects remote input."""

    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(code)


@dataclass(frozen=True)
class _Series:
    identity: str = field(repr=False)
    scope_identity: str = field(repr=False)
    finish_reason_class: str = field(repr=False)
    value: float


@dataclass(frozen=True, slots=True)
class MetricsSnapshot:
    """An immutable, in-memory snapshot of recognized vLLM series.

    Series identities are keyed hashes and are deliberately excluded from the
    representation and public projection.  They exist only to detect a worker
    label-topology change or observed per-series counter decrease before values
    are aggregated. They cannot identify a same-label source replacement.
    """

    recognized_samples: int
    available_families: tuple[str, ...]
    _families: tuple[tuple[str, tuple[_Series, ...]], ...] = field(
        repr=False
    )

    def _family(self, name: str) -> Mapping[str, float] | None:
        for family_name, series in self._families:
            if family_name == name:
                return MappingProxyType(
                    {item.identity: item.value for item in series}
                )
        return None

    def public_summary(self) -> dict[str, object]:
        """Return only allowlisted availability metadata, never raw labels."""

        _validate_snapshot(self)
        return {
            "recognized_samples": self.recognized_samples,
            "available_families": list(self.available_families),
        }


